#!/usr/bin/env node
// Regenerates the placement page's tables from the plugin's own source.
//
// The regexes are deliberately identical to the ones in the plugin's
// tests/Unit/Compliance/HelpTabAccuracyTest.php, so this file and that test
// agree by construction. If the plugin changes the shape of those constants,
// both break at once — which is the point.

const fs = require('fs');
const https = require('https');

const PLUGIN_REF = fs
  .readFileSync(require('path').join(__dirname, '..', 'plugin-ref.txt'), 'utf8')
  .trim();

const SRC =
  `https://raw.githubusercontent.com/MaxHandMade/mhm-currency-switcher/${PLUGIN_REF}/admin-app/src/components/tabs/HowToUse.jsx`;

function fetch(url) {
  return new Promise((resolve, reject) => {
    https
      .get(url, (res) => {
        if (res.statusCode !== 200) {
          reject(new Error(`GET ${url} -> HTTP ${res.statusCode}`));
          return;
        }
        let body = '';
        res.on('data', (c) => (body += c));
        res.on('end', () => resolve(body));
      })
      .on('error', reject);
  });
}

function parse(jsx) {
  const samples = [];
  const re = /\{\s*shortcode:\s*'([a-z_]+)',\s*attrs:\s*\[([^\]]*)\]\s*,?\s*\}/g;
  let m;
  while ((m = re.exec(jsx)) !== null) {
    const attrs = [...m[2].matchAll(/'([a-z_]+)'/g)].map((a) => a[1]);
    samples.push({ shortcode: m[1], attrs });
  }

  const wm = jsx.match(/export const ELEMENTOR_WIDGETS = \[([^\]]*)\]/);
  if (!wm) throw new Error('ELEMENTOR_WIDGETS not found — the source shape changed.');
  const widgets = [...wm[1].matchAll(/'([^']+)'/g)].map((a) => a[1]);

  if (samples.length !== 2) {
    throw new Error(`expected 2 placement samples, found ${samples.length}`);
  }
  return { samples, widgets };
}

// Labels are per-locale. The block is generated ONCE PER TARGET FILE, not once
// for both: an earlier draft computed it a single time and wrote it verbatim to
// both pages, so the English page carried Turkish table headers.
const LABELS = {
  en: {
    shortcode: 'Shortcode',
    attrs: 'Attributes',
    widget: 'Elementor widget',
    footer: (sw, pr) => `Switcher shortcode: \`[${sw}]\` · Price list: \`[${pr}]\``,
  },
  tr: {
    shortcode: 'Kısa kod',
    attrs: 'Öznitelikler',
    widget: 'Elementor widget\'ı',
    footer: (sw, pr) => `Switcher kısa kodu: \`[${sw}]\` · Fiyat listesi: \`[${pr}]\``,
  },
};

function table({ samples, widgets }, locale) {
  const L = LABELS[locale];
  const [sw, prices] = samples;
  const lines = [];
  lines.push('<!-- generated by scripts/generate-placement-page.js — do not edit by hand -->');
  lines.push('');
  lines.push(`| ${L.shortcode} | ${L.attrs} |`);
  lines.push('|---|---|');
  for (const s of samples) {
    lines.push(`| \`[${s.shortcode}]\` | ${s.attrs.map((a) => '`' + a + '`').join(', ')} |`);
  }
  lines.push('');
  lines.push(`| ${L.widget} |`);
  lines.push('|---|');
  for (const w of widgets) lines.push(`| ${w} |`);
  lines.push('');
  lines.push(L.footer(sw.shortcode, prices.shortcode));
  return lines.join('\n');
}

(async () => {
  const jsx = await fetch(SRC);
  const parsed = parse(jsx);

  for (const [p, locale] of [
    ['docs/yerlestirme.md', 'en'],
    ['i18n/tr/docusaurus-plugin-content-docs/current/yerlestirme.md', 'tr'],
  ]) {
    const generated = table(parsed, locale);
    const current = fs.readFileSync(p, 'utf8');
    const marker = '<!-- BEGIN GENERATED -->';
    const end = '<!-- END GENERATED -->';
    const before = current.split(marker)[0];
    const after = current.split(end)[1];
    if (after === undefined) throw new Error(`${p} is missing the generated-block markers.`);
    fs.writeFileSync(p, `${before}${marker}\n${generated}\n${end}${after}`);
  }
  console.log('placement tables regenerated');
})();
